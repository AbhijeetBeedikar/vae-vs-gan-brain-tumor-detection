"""Figures: reconstructions during training, and qualitative/quantitative results."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # render to files; no display needed
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402


def _save(fig, path: str | Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120, bbox_inches="tight")
    plt.close(fig)


def save_reconstruction_grid(x, x_hat, path) -> None:
    """Two rows: input slices on top, their reconstructions below."""
    x, x_hat = np.asarray(x)[:, 0], np.asarray(x_hat)[:, 0]
    n = len(x)
    fig, axes = plt.subplots(2, n, figsize=(1.6 * n, 3.4))
    for i in range(n):
        for row, img in enumerate((x[i], x_hat[i])):
            axes[row, i].imshow(img, cmap="gray", vmin=0, vmax=1)
            axes[row, i].axis("off")
    axes[0, 0].set_title("input", fontsize=8, loc="left")
    axes[1, 0].set_title("reconstruction", fontsize=8, loc="left")
    _save(fig, path)


def save_sample_grid(samples, path, ncols: int = 8) -> None:
    """Grid of images generated by the GAN from random noise."""
    samples = np.asarray(samples)[:, 0]
    nrows = int(np.ceil(len(samples) / ncols))
    fig, axes = plt.subplots(nrows, ncols, figsize=(1.5 * ncols, 1.5 * nrows))
    for ax, img in zip(axes.flat, samples):
        ax.imshow(img, cmap="gray", vmin=0, vmax=1)
    for ax in axes.flat:
        ax.axis("off")
    _save(fig, path)


def save_example_panel(examples: dict, path, title: str = "") -> None:
    """One row per example slice: input | reconstruction | anomaly map | prediction vs truth.

    In the last column the expert outline is green and the predicted tumour is red.
    """
    x, x_hat, amap = examples["image"], examples["recon"], examples["map"]
    pred, label = examples["pred"], examples["label"]
    n = len(x)
    fig, axes = plt.subplots(n, 4, figsize=(8, 2.1 * n))
    axes = np.atleast_2d(axes)
    vmax = np.percentile(amap, 99.9) if amap.max() > 0 else 1.0
    for i in range(n):
        axes[i, 0].imshow(x[i], cmap="gray", vmin=0, vmax=1)
        axes[i, 1].imshow(x_hat[i], cmap="gray", vmin=0, vmax=1)
        axes[i, 2].imshow(amap[i], cmap="inferno", vmin=0, vmax=vmax)
        axes[i, 3].imshow(x[i], cmap="gray", vmin=0, vmax=1)
        axes[i, 3].contour(label[i], levels=[0.5], colors="lime", linewidths=1)
        axes[i, 3].contour(pred[i], levels=[0.5], colors="red", linewidths=1)
    for ax, t in zip(axes[0], ("input", "reconstruction", "anomaly map", "pred (red) / truth (green)")):
        ax.set_title(t, fontsize=9)
    for ax in axes.flat:
        ax.axis("off")
    if title:
        fig.suptitle(title)
    _save(fig, path)


def save_comparison_panel(per_model: dict[str, dict], path) -> None:
    """Side-by-side comparison of all models on the same test slices.

    Columns: input + truth, then for each model its reconstruction and anomaly map.
    """
    names = list(per_model)
    first = per_model[names[0]]
    n = len(first["image"])
    ncols = 1 + 2 * len(names)
    fig, axes = plt.subplots(n, ncols, figsize=(1.8 * ncols, 1.9 * n))
    axes = np.atleast_2d(axes)
    for i in range(n):
        axes[i, 0].imshow(first["image"][i], cmap="gray", vmin=0, vmax=1)
        axes[i, 0].contour(first["label"][i], levels=[0.5], colors="lime", linewidths=0.8)
        for m, name in enumerate(names):
            ex = per_model[name]
            vmax = np.percentile(ex["map"], 99.9) if ex["map"].max() > 0 else 1.0
            axes[i, 1 + 2 * m].imshow(ex["recon"][i], cmap="gray", vmin=0, vmax=1)
            axes[i, 2 + 2 * m].imshow(ex["map"][i], cmap="inferno", vmin=0, vmax=vmax)
            axes[i, 2 + 2 * m].contour(ex["pred"][i], levels=[0.5], colors="cyan", linewidths=0.6)
    axes[0, 0].set_title("input + truth", fontsize=8)
    for m, name in enumerate(names):
        axes[0, 1 + 2 * m].set_title(f"{name} recon", fontsize=8)
        axes[0, 2 + 2 * m].set_title(f"{name} map", fontsize=8)
    for ax in axes.flat:
        ax.axis("off")
    _save(fig, path)


def save_metric_bars(summary: dict[str, dict], metrics: list[str], path) -> None:
    """Grouped bar chart: one group per metric, one bar per model."""
    names = list(summary)
    x = np.arange(len(metrics))
    width = 0.8 / len(names)
    fig, ax = plt.subplots(figsize=(1.6 * len(metrics) + 2, 3.6))
    for i, name in enumerate(names):
        vals = [summary[name].get(m, np.nan) for m in metrics]
        bars = ax.bar(x + (i - (len(names) - 1) / 2) * width, vals, width, label=name)
        ax.bar_label(bars, fmt="%.2f", fontsize=6, padding=1)
    ax.set_xticks(x, metrics, rotation=20, ha="right")
    ax.set_ylim(0, 1.05)
    ax.legend(fontsize=8, ncol=len(names), loc="upper center", bbox_to_anchor=(0.5, 1.15), frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    _save(fig, path)


def save_training_curves(histories: dict[str, list], path) -> None:
    """Validation reconstruction error per epoch for each model."""
    fig, ax = plt.subplots(figsize=(5, 3.4))
    for name, hist in histories.items():
        pts = [(h["epoch"], h["val_mse"]) for h in hist if "val_mse" in h]
        if pts:
            ep, mse = zip(*pts)
            ax.plot(ep, mse, label=name)
    ax.set_xlabel("epoch (f-AnoGAN: encoder stage)")
    ax.set_ylabel("healthy validation MSE")
    ax.set_yscale("log")
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    _save(fig, path)
